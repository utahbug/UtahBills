import {execFileSync} from 'node:child_process';
import './validate.mjs';
import {build} from 'esbuild';
import {mkdir,copyFile,cp,rm,readFile,writeFile} from 'node:fs/promises';
import path from 'node:path';
execFileSync(process.env.PYTHON||(process.platform==='win32'?'python':'python3'),['tests/vote_data.py'],{stdio:'inherit'});
const project=process.cwd(),output=path.resolve(project,'dist');
if(output!==path.join(project,'dist')||path.dirname(output)!==project)throw Error('Unsafe output directory');
await rm(output,{recursive:true,force:true});
await mkdir(output,{recursive:true});
await build({entryPoints:['app.js'],bundle:true,format:'esm',outfile:'dist/app.js',minify:true});
for(const f of ['index.html','styles.css']) await copyFile(f,'dist/'+f);
await cp('data','dist/data',{recursive:true});
const examples=JSON.parse(await readFile('data/bills.json','utf8'));
await mkdir('dist/data/examples',{recursive:true});
for(const b of examples)await writeFile('dist/data/examples/'+b.billNumber+'.json',JSON.stringify(b));
await writeFile('dist/data/examples-ui.json',JSON.stringify(examples.map(b=>Object.fromEntries(['billNumber','summary','summaryVersion','extra','topic','status'].map(k=>[k,b[k]])))));
const calendar=JSON.parse(await readFile('data/calendar.json','utf8'));
const {agendas,...calendarView}=calendar;
calendarView.sources=calendar.sources.map(({body,...source})=>source);
await writeFile('dist/data/calendar-ui.json',JSON.stringify(calendarView));
execFileSync(process.env.PYTHON||(process.platform==='win32'?'python':'python3'),['scripts/catalog_model.py','--build'],{stdio:'inherit'});
execFileSync(process.env.PYTHON||(process.platform==='win32'?'python':'python3'),['scripts/foundation_model.py','--build','--report'],{stdio:'inherit'});
execFileSync(process.env.PYTHON||(process.platform==='win32'?'python':'python3'),['scripts/activity_model.py'],{stdio:'inherit'});
execFileSync(process.env.PYTHON||(process.platform==='win32'?'python':'python3'),['scripts/version_model.py'],{stdio:'inherit'});
await cp('assets','dist/assets',{recursive:true});
await copyFile('node_modules/lucide/LICENSE','dist/LUCIDE-LICENSE.txt');
console.log('Built static site in dist; all assets use relative URLs.');

// Every normal or scheduled publication includes both permanent environments.
await import('./package-review.mjs');
